//! UNIX 98 PTY / Windows ConPTY Pseudo-Terminal Subsystem
//!
//! Bare-metal no_std pure Rust implementation of terminal line discipline
//! and bidirectional master-slave pseudo-terminal driver for CorOS.
//! Connects the GUI Corpus Terminal emulator directly to user processes.

#![allow(dead_code)]

use alloc::vec::Vec;
use alloc::collections::VecDeque;

/// Window Size Structure (TIOCGWINSZ / TIOCSWINSZ)
#[repr(C)]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct WinSize {
    pub ws_row: u16,
    pub ws_col: u16,
    pub ws_xpixel: u16,
    pub ws_ypixel: u16,
}

/// Termios Input/Output Flags
pub const ECHO: u32 = 0x0001;     // Echo input characters
pub const ICANON: u32 = 0x0002;   // Canonical mode (line-by-line input)
pub const ISIG: u32 = 0x0004;     // Enable signals (Ctrl+C, Ctrl+Z)
pub const OPOST: u32 = 0x0008;    // Enable output post-processing
pub const ONLCR: u32 = 0x0010;    // Translate NL to CR-NL on output
pub const ICRNL: u32 = 0x0020;    // Translate CR to NL on input

/// Termios State Machine
#[derive(Debug, Clone, Copy)]
pub struct Termios {
    pub flags: u32,
    pub c_cc_intr: u8,   // Ctrl+C (0x03)
    pub c_cc_quit: u8,   // Ctrl+\ (0x1C)
    pub c_cc_erase: u8,  // Backspace (0x7F or 0x08)
    pub c_cc_kill: u8,   // Ctrl+U (0x15)
    pub c_cc_eof: u8,    // Ctrl+D (0x04)
}

impl Default for Termios {
    fn default() -> Self {
        Self {
            flags: ECHO | ICANON | ISIG | OPOST | ONLCR | ICRNL,
            c_cc_intr: 0x03,
            c_cc_quit: 0x1C,
            c_cc_erase: 0x08,
            c_cc_kill: 0x15,
            c_cc_eof: 0x04,
        }
    }
}

/// Signals Generated by PTY Line Discipline
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PtySignal {
    SigInt,  // Interrupt (Ctrl+C)
    SigQuit, // Quit (Ctrl+\)
    SigTstp, // Stop / Suspend (Ctrl+Z)
}

/// Terminal Line Discipline & Circular Buffer
pub struct PtyMasterSlavePair {
    pub pty_id: u32,
    pub termios: Termios,
    pub winsize: WinSize,
    
    // Master-to-Slave stream (user typing into GUI terminal -> process stdin)
    slave_input_line: Vec<u8>,
    slave_input_queue: VecDeque<u8>,

    // Slave-to-Master stream (process stdout -> GUI terminal display)
    master_output_queue: VecDeque<u8>,

    pub pending_signal: Option<PtySignal>,
}

impl PtyMasterSlavePair {
    pub fn new(pty_id: u32, rows: u16, cols: u16) -> Self {
        Self {
            pty_id,
            termios: Termios::default(),
            winsize: WinSize {
                ws_row: rows,
                ws_col: cols,
                ws_xpixel: cols * 8,
                ws_ypixel: rows * 16,
            },
            slave_input_line: Vec::new(),
            slave_input_queue: VecDeque::new(),
            master_output_queue: VecDeque::new(),
            pending_signal: None,
        }
    }

    /// Master writes bytes (e.g. keyboard keystroke from GUI terminal)
    pub fn master_write(&mut self, data: &[u8]) {
        for &byte in data {
            let mut ch = byte;

            // Handle signal characters in ISIG mode
            if (self.termios.flags & ISIG) != 0 {
                if ch == self.termios.c_cc_intr {
                    self.pending_signal = Some(PtySignal::SigInt);
                    if (self.termios.flags & ECHO) != 0 {
                        self.master_output_queue.extend(b"^C\r\n");
                    }
                    self.slave_input_line.clear();
                    continue;
                } else if ch == self.termios.c_cc_quit {
                    self.pending_signal = Some(PtySignal::SigQuit);
                    continue;
                }
            }

            // ICRNL: Map Carriage Return to Newline
            if (self.termios.flags & ICRNL) != 0 && ch == b'\r' {
                ch = b'\n';
            }

            // Canonical (cooked) mode line editing
            if (self.termios.flags & ICANON) != 0 {
                if ch == self.termios.c_cc_erase || ch == 0x7F {
                    // Backspace
                    if !self.slave_input_line.is_empty() {
                        self.slave_input_line.pop();
                        if (self.termios.flags & ECHO) != 0 {
                            self.master_output_queue.extend(b"\x08 \x08");
                        }
                    }
                } else if ch == self.termios.c_cc_kill {
                    // Ctrl+U: Erase whole line
                    let len = self.slave_input_line.len();
                    self.slave_input_line.clear();
                    if (self.termios.flags & ECHO) != 0 {
                        for _ in 0..len {
                            self.master_output_queue.extend(b"\x08 \x08");
                        }
                    }
                } else if ch == self.termios.c_cc_eof {
                    // Ctrl+D: Commit line without newline
                    for b in self.slave_input_line.drain(..) {
                        self.slave_input_queue.push_back(b);
                    }
                } else if ch == b'\n' {
                    // Newline: Commit line and echo
                    self.slave_input_line.push(b'\n');
                    for b in self.slave_input_line.drain(..) {
                        self.slave_input_queue.push_back(b);
                    }
                    if (self.termios.flags & ECHO) != 0 {
                        if (self.termios.flags & ONLCR) != 0 {
                            self.master_output_queue.extend(b"\r\n");
                        } else {
                            self.master_output_queue.push_back(b'\n');
                        }
                    }
                } else {
                    // Regular printable character
                    self.slave_input_line.push(ch);
                    if (self.termios.flags & ECHO) != 0 {
                        self.master_output_queue.push_back(ch);
                    }
                }
            } else {
                // Raw mode: pass byte directly to slave
                self.slave_input_queue.push_back(ch);
                if (self.termios.flags & ECHO) != 0 {
                    self.master_output_queue.push_back(ch);
                }
            }
        }
    }

    /// Slave reads bytes (e.g. process reading stdin)
    pub fn slave_read(&mut self, buf: &mut [u8]) -> usize {
        let count = buf.len().min(self.slave_input_queue.len());
        for i in 0..count {
            buf[i] = self.slave_input_queue.pop_front().unwrap();
        }
        count
    }

    /// Slave writes bytes (e.g. process writing stdout/stderr)
    pub fn slave_write(&mut self, data: &[u8]) {
        for &byte in data {
            if byte == b'\n' && (self.termios.flags & OPOST) != 0 && (self.termios.flags & ONLCR) != 0 {
                self.master_output_queue.push_back(b'\r');
                self.master_output_queue.push_back(b'\n');
            } else {
                self.master_output_queue.push_back(byte);
            }
        }
    }

    /// Master reads bytes (e.g. GUI terminal rendering output characters)
    pub fn master_read(&mut self, buf: &mut [u8]) -> usize {
        let count = buf.len().min(self.master_output_queue.len());
        for i in 0..count {
            buf[i] = self.master_output_queue.pop_front().unwrap();
        }
        count
    }

    /// Resize window geometry
    pub fn set_window_size(&mut self, rows: u16, cols: u16) {
        self.winsize.ws_row = rows;
        self.winsize.ws_col = cols;
        self.winsize.ws_xpixel = cols * 8;
        self.winsize.ws_ypixel = rows * 16;
    }
}
